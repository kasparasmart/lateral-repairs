#!/usr/bin/env python3
"""
Builds the production upload package for plain Apache hosting (Serveriai.lt).

  python3 tools/build-products.py   # regenerate pages first
  python3 tools/build-deploy.py

Writes deployment/public_html/ (exactly what gets uploaded to the document root) and
deployment/MANIFEST.sha256. Only allow-listed files are copied: no Vercel config,
tooling, docs or .htaccess (server config is merged by hand, see deployment/DEPLOY.md).
"""
import hashlib
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "deployment" / "public_html"
MANIFEST = ROOT / "deployment" / "MANIFEST.sha256"

INCLUDE = [
    "index.html",
    "privacy.html",
    "cookies.html",
    "sitemap-lr.xml",
    "products/*.html",
    "lr-assets/css/styles.css",
    "lr-assets/js/main.js",
    "lr-assets/vendor/three.min.js",
    "lr-assets/fonts/fonts.css",
    "lr-assets/fonts/*.woff2",
    "lr-assets/datasheets/*.pdf",
    "lr-assets/certs/*.pdf",
    "lr-assets/images/*.png",
    "lr-assets/images/*.svg",
    "lr-assets/images/products/*.jpg",
    "lr-assets/images/gallery/*.jpg",
    "lr-assets/images/certs/*",
]
EXCLUDE = {"lr-assets/images/logo.png"}  # not referenced by any page

# Names that belong to the existing CMS Made Simple / PHP site. The package must never contain
# them, so an upload can't replace backend files. All frontend assets live in lr-assets/
# because CMSMS 2.x already uses a top-level assets/ directory.
BACKEND_NAMES = re.compile(
    r"(^|/)(index\.php|config\.php|.*\.php|\.htaccess|\.user\.ini|php\.ini|.*\.sql(\.gz)?)$"
    r"|^(admin|modules|plugins|vendor|uploads|lib|tmp|doc|install|assets|cgi-bin|\.well-known)/"
)

FORBIDDEN = re.compile(r"vercel\.app|vercel\.com|localhost|127\.0\.0\.1|0\.0\.0\.0|https?://lateralrepairs\.com|http://www\.lateralrepairs")
TEXT_EXT = {".html", ".css", ".js", ".txt", ".xml"}


def collect():
    files = set()
    for pattern in INCLUDE:
        matches = [p for p in ROOT.glob(pattern) if p.is_file()]
        if not matches:
            raise SystemExit(f"allow-list pattern matched nothing: {pattern}")
        files.update(p.relative_to(ROOT).as_posix() for p in matches)
    return sorted(files - EXCLUDE)


def write_htaccess_reference():
    """deployment/htaccess-additions.conf: the exact lines tools/merge_htaccess.py inserts (single source)."""
    sys.path.insert(0, str(ROOT / "tools"))
    import merge_htaccess as mh
    (ROOT / "deployment" / "htaccess-additions.conf").write_text(
        "# GENERATED by tools/build-deploy.py from tools/merge_htaccess.py - do not edit by hand.\n"
        "# Preferred: python3 tools/merge_htaccess.py production.htaccess merged.htaccess\n"
        "# Manual merge into the EXISTING production .htaccess (never replace the file):\n#\n"
        "# BLOCK 1 - insert directly AFTER the existing line\n"
        "#     RewriteRule ^(.*)index.php$ /$1 [R=301,L]\n"
        "# (i.e. after the www / HTTPS / index.php redirects, BEFORE the CMS trailing-slash and page rules)\n"
        + mh.ROOT_BLOCK
        + "\n# BLOCK 2 - append at the very END of the file\n"
        + mh.CACHE_BLOCK,
        encoding="utf-8")


def main():
    files = collect()
    clash = [f for f in files if BACKEND_NAMES.search(f)]
    if clash:
        raise SystemExit(f"refusing to package backend/CMS paths: {clash}")

    problems = []
    for rel in files:
        if pathlib.Path(rel).suffix in TEXT_EXT and rel != "lr-assets/vendor/three.min.js":
            for n, line in enumerate((ROOT / rel).read_text(encoding="utf-8").splitlines(), 1):
                if FORBIDDEN.search(line):
                    problems.append(f"{rel}:{n}: {FORBIDDEN.search(line).group(0)}")
    if problems:
        print("refusing to package development/Vercel URLs:", *problems, sep="\n  ")
        sys.exit(1)

    if OUT.exists():
        shutil.rmtree(OUT)
    lines = []
    for rel in files:
        dst = OUT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, dst)
        data = dst.read_bytes()
        lines.append(f"{hashlib.sha256(data).hexdigest()}  {rel}")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # robots.txt is NOT part of the upload: production may already have one (see DEPLOY.md)
    write_htaccess_reference()
    shutil.copyfile(ROOT / "robots.txt", ROOT / "deployment" / "robots.txt")

    size = sum((OUT / f).stat().st_size for f in files)
    print(f"packaged {len(files)} files ({size / 1048576:.1f} MB) -> deployment/public_html/")
    print("wrote deployment/MANIFEST.sha256")

    markers = [
        f"{rel}: {m}"
        for rel in files if rel.endswith(".html")
        for m in re.findall(r"\[TO CONFIRM[^\]]*\]", (ROOT / rel).read_text(encoding="utf-8"))
    ]
    if markers:
        print(f"\nWARNING: {len(markers)} unresolved TO CONFIRM marker(s) — resolve before upload:")
        for m in markers:
            print("  " + m)


if __name__ == "__main__":
    main()
